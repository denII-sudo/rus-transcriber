"""Пол говорящего по тексту: глагол прошедшего времени или краткое прилагательное рядом с «я».

«я поняла», «я не боялась», «я сама» -> 'f';  «я думал», «я был», «я сам» -> 'm'.
Чужая речь не учитывается: текст в кавычках и после двоеточия («Борис сказал: я бы не поехала»).
Правила без словаря: признак засчитывается, только если слово стоит в пределах трёх слов после «я»
в той же части фразы (до знака препинания).
"""
import re

FEM_ADJ = {"рада", "сама", "одна", "уверена", "готова", "должна", "согласна", "довольна", "виновата",
           "права", "больна", "занята", "свободна", "голодна", "влюблена", "обязана", "счастлива"}
MASC_ADJ = {"рад", "сам", "один", "уверен", "готов", "должен", "согласен", "доволен", "виноват",
            "прав", "болен", "занят", "свободен", "голоден", "влюблён", "влюблен", "обязан", "счастлив"}
SHORT_MASC = {"был", "пил", "жил", "мыл", "бил", "шил", "выл", "лил", "ныл", "гнил", "плыл", "слыл"}
NOT_VERB = {"пола", "стола", "зала", "мала", "сила", "дела", "мыла", "пила", "вилла", "школа", "скала",
            "тела", "села", "кола", "футбола", "игла", "мгла", "стрела", "мула", "пчела", "смола",
            "зал", "пол", "стол", "мол", "бал", "вол", "кол", "тол", "дол",
            "футбол", "сигнал", "канал", "финал", "журнал", "материал", "идеал", "пенал",
            "металл", "овал", "вокзал", "подвал", "провал", "капитал", "интервал", "персонал", "шакал"}
VOW = "аеёиоуыэюя"
SPLIT = re.compile(r"[.,!?;:—–\-«»\"()…]")
TOK = re.compile(r"[а-яё]+")


def _strip_reported(text):
    t = re.sub(r"«[^»]*»", " . ", text)
    t = re.sub(r"\"[^\"]*\"", " . ", t)
    t = re.sub(r":[^.!?]*", " . ", t)   # после двоеточия — чаще чужая речь
    return t


def _word_gender(w):
    if w in NOT_VERB:
        return None
    if w in FEM_ADJ:
        return "f"
    if w in MASC_ADJ:
        return "m"
    if len(w) >= 4 and (w.endswith("лась") or (w.endswith("ла") and w[-3] in VOW)):
        return "f"
    if w.endswith("лся") and len(w) >= 5 and w[-4] in VOW:
        return "m"
    if w.endswith("л") and w[-2:-1] and w[-2] in VOW and (len(w) >= 5 or w in SHORT_MASC):
        return "m"
    return None


def evidence(text):
    """-> ('f'|'m'|None, [слова-признаки])"""
    found = []
    for part in SPLIT.split(_strip_reported(text.lower())):
        toks = TOK.findall(part)
        for i, w in enumerate(toks):
            if w != "я":
                continue
            for nxt in toks[i + 1:i + 4]:
                if nxt in ("ты", "он", "она", "вы", "они", "мы"):
                    break
                g = _word_gender(nxt)
                if g:
                    found.append((g, nxt))
                    break
    gs = {g for g, _ in found}
    if len(gs) == 1:
        return gs.pop(), [w for _, w in found]
    return None, [w for _, w in found]
